#fazer um algoritmo que some dois numeros e multiplique o resultado pelo primeiro numero.
#entrada
num1 = int(input("Informe o primeiro número: "))
num2 = int(input("Informe o segundo numero: "))
#processamento
soma = num1 + num2
multiplicação = soma * num1
#saida
print("O resultado da multiplicação é {0}".format(multiplicação))